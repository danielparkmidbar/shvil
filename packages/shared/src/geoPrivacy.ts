/**
 * 위치 프라이버시 눈금화 (R-4 확정, 2026-07-14 다니엘 쌤 — 서비스 재조정 설계 §6).
 *
 * 공개 웹/앱에는 엔젤의 **대략 위치(~1km 눈금) + 닉네임만** 공개한다.
 * 주소·전화번호 등 정확한 정보는 승인된 두 개인 간에만 지갑 E2E 메시지로 전달한다.
 *
 * 원칙: **서버는 엔젤의 정확한 좌표를 아예 모른다.**
 * - 지갑이 전송 전에 눈금화한다 (정확 좌표는 지갑 로컬 DB에만).
 * - 서버도 수신 시 방어적으로 다시 눈금화한다 (클라이언트 불신 — 이중 방어).
 *
 * 눈금 크기 0.01° ≈ 위도 1.1km, 이스라엘 위도(≈32°N)에서 경도 ≈0.95km.
 */

/** 프라이버시 눈금 크기 (도 단위). 0.01° ≈ 1km. */
export const PRIVACY_GRID_DEG = 0.01;

/**
 * 좌표를 프라이버시 눈금(소수 둘째 자리)으로 반올림한다.
 * 부동소수 오차를 피하려 0.01을 곱하는 대신 ×100 → round → ÷100 을 쓴다.
 * 멱등: snap(snap(p)) == snap(p).
 */
export function snapToPrivacyGrid(lat: number, lon: number): { lat: number; lon: number } {
  return {
    lat: Math.round(lat * 100) / 100,
    lon: Math.round(lon * 100) / 100,
  };
}
